"""Layer 3: the generated agent contract (DESIGN §2, §10).

`agent/AGENTS.md` is the schema doc — what this bundle holds and how to read it.
`agent/mcp_server.py` is the launcher a `.mcp.json` entry points at, which is what
makes any MCP-capable agent a consumer of the bundle with no ragged-specific code.

Regenerated on every ingest and by `ragged agent`, and deliberately carries no
timestamp: the same bundle must regenerate to the same bytes, or a committed
contract churns on every build.
"""

from __future__ import annotations

import json
import posixpath
import sys
from collections import Counter
from pathlib import Path

from .. import okf
from ..config import Config
from ..okf import Concept

AGENTS_NAME = "AGENTS.md"
SERVER_NAME = "mcp_server.py"
MCP_CONFIG_NAME = ".mcp.json"
SERVER_KEY = "ragged"

LAUNCHER = '''"""Generated by ragged — the stdio MCP server over this bundle.

Registered by the `.mcp.json` entry beside it. Edits are overwritten on the next
`ragged build`; the server itself is `ragged.agent.server`.
"""

from pathlib import Path

from ragged.agent.server import main

main(Path(__file__).resolve().parent.parent)
'''


def write_contract(config: Config) -> list[Path]:
    agent_root = config.project_root / "agent"
    return [
        _write(agent_root / AGENTS_NAME, render_agents_md(config)),
        _write(agent_root / SERVER_NAME, LAUNCHER),
        _write(config.project_root / MCP_CONFIG_NAME, render_mcp_json(config)),
    ]


def render_mcp_json(config: Config) -> str:
    """The registration entry, merged into whatever else is already registered."""
    path = config.project_root / MCP_CONFIG_NAME
    existing: dict = {}
    if path.exists():
        try:
            loaded = json.loads(path.read_text(encoding="utf-8-sig"))
            existing = loaded if isinstance(loaded, dict) else {}
        except (OSError, ValueError):
            existing = {}
    servers = dict(existing.get("mcpServers") or {})
    servers[SERVER_KEY] = {
        "command": _interpreter(config.project_root),
        "args": [f"agent/{SERVER_NAME}"],
    }
    return json.dumps({**existing, "mcpServers": servers}, indent=2) + "\n"


def _interpreter(project_root: Path) -> str:
    """A repo-local venv gives a relative command, so the entry survives a clone."""
    exe = Path(sys.executable)
    if exe.is_relative_to(project_root):
        return exe.relative_to(project_root).as_posix()
    return exe.as_posix()


def render_agents_md(config: Config) -> str:
    concepts = okf.read_concepts(config.bundle_root)
    bundle = config.bundle.root
    lines = [
        f"# {config.bundle_title} — agent contract",
        "",
        f"Generated by ragged from `{bundle}/`. Regenerated on every `ragged build` "
        "and by `ragged agent`, so edits here are overwritten.",
        "",
        f"`{bundle}/` is an **Open Knowledge Format v{config.bundle.okf_version}** bundle: "
        f"markdown concepts with YAML frontmatter, an `index.md` per directory, and a "
        f"`log.md`. It holds **{len(concepts)} concept(s)**. Nothing else is needed to read "
        "it — no SDK, no database, no embeddings.",
        "",
        "## How to query it",
        "",
        f"1. **Read `{bundle}/index.md` first.** It lists every top-level concept with its "
        "own title and description. An entry that ends `([n more](./x/index.md))` owns a "
        "subdirectory — follow it down.",
        "2. **Then read whole concept files.** A concept is the unit of knowledge here, and "
        "its frontmatter carries the provenance its body depends on. Do not search for "
        "chunks and do not read fragments: read the file.",
        "3. **Follow the cross-links in the prose.** They are bundle-absolute "
        "(`/finance/pricing.md`) and inline, because a link asserts a relationship and the "
        "sentence around it says which. There is no \"Related\" section by design.",
        "",
        "`search` is a way in, not a substitute for the indexes: it returns pointers — "
        "concept id, title, description, score — and never a body. You decide what to read.",
        "",
        "## Structure",
        "",
        "```",
        *_structure(bundle, concepts),
        "```",
        "",
        "## Type vocabulary",
        "",
        "`type` is free-form in OKF; this is the vocabulary this bundle actually uses.",
        "",
        "| type | concepts |",
        "|---|---|",
        *_types(concepts),
        "",
        "## Trust",
        "",
        "| field | what it means |",
        "|---|---|",
        "| `status: draft` | ragged wrote it and nobody has confirmed it. The default. |",
        "| `status: stable` | a human promoted it by editing the file. |",
        "| `status: deprecated` | its source is gone. Kept for links and history. |",
        "| no `verified` block | trust tier **unverified**. |",
        "| `verified` by `human:…` | trust tier **human-reviewed**. |",
        "| `verified` by anything else | trust tier **machine-confirmed**. |",
        "",
        "**Never write a `verified` block.** It records a confirmation event that actually "
        "happened; writing one because the content looks correct forges the human-reviewed "
        "tier. ragged never writes it and neither should you — a human promotes a concept "
        "by editing the file.",
        "",
        "## Operations",
        "",
        "Three, over the MCP server registered in `.mcp.json`.",
        "",
        "| tool | signature | credential |",
        "|---|---|---|",
        "| `search` | `(query: str, k: int = 8)` → pointers: `concept_id`, `title`, "
        "`description`, `score` | none |",
        "| `read_concept` | `(concept_id: str)` → the raw file, frontmatter included | none |",
        "| `ingest` | `(paths: list[str] \\| None)` → what the run wrote. `null` = full sweep | "
        "**required** |",
        "| `lint` | `()` → conformance, ghost edges, stale concepts, orphans | none |",
        "",
        "**Only `ingest` needs a credential.** It runs the synthesis pipeline, which calls a "
        "model; without a key it fails with that message and changes nothing. Querying and "
        "linting an existing bundle are entirely offline.",
        "",
        f"- **query** — `search`, then `read_concept` on what it points at (and on "
        f"`{bundle}/index.md` itself).",
        "- **ingest** — re-reads `sources/`, and only pays for the files whose bytes "
        "changed. A concept a human edited is never overwritten.",
        "- **lint** — okflint conformance plus ghost edges (similar pairs nobody linked), "
        "stale concepts, and orphans (concepts nothing links to). Ghost edges come from "
        "`.ragged/graph.json`, so run `ragged index` if it reports having none to read.",
        "",
        "## Registering the server",
        "",
        f"`{MCP_CONFIG_NAME}` at the project root points at `agent/{SERVER_NAME}`. The "
        'server needs the MCP SDK, which is an optional extra: `pip install -e ".[mcp]"`.',
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


def _structure(bundle: str, concepts: list[Concept]) -> list[str]:
    counts: Counter[str] = Counter()
    for concept in concepts:
        counts[posixpath.dirname(concept.concept_id)] += 1
    lines = [
        f"{bundle}/",
        "  index.md",
        "  log.md",
        f"  ({counts.get('', 0)} concept(s) at the root)",
    ]
    for directory in sorted(d for d in counts if d):
        indent = "  " * (directory.count("/") + 1)
        lines.append(f"{indent}{directory.rsplit('/', 1)[-1]}/  ({counts[directory]} concept(s))")
    return lines


def _types(concepts: list[Concept]) -> list[str]:
    counts = Counter(concept.type for concept in concepts)
    return [f"| `{name}` | {count} |" for name, count in sorted(counts.items())]


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return path
